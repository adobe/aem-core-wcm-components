/* eslint-env node */
"use strict";

/*
 * Deletes the client libraries generated by clientlib.config.js under src/content (they are not tracked by Git).
 * aem-clientlib-generator only replaces the folders it is currently configured for, so a client library folder that
 * was moved or removed from the configuration would otherwise remain in the workspace and be packaged.
 */
const fs = require("fs");
const path = require("path");

// only contains generated client libraries, see the core.wcm.components.commons.datalayer.* entry in .gitignore
const GENERATED_DIRS = [
    path.join(__dirname, "..", "src/content/jcr_root/apps/core/wcm/components/commons/datalayer")
];

GENERATED_DIRS.forEach(function(dir) {
    if (fs.existsSync(dir)) {
        fs.rmSync(dir, { recursive: true, force: true });
        console.log("Deleted " + dir);
    }
});
