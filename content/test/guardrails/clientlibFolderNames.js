/**
 * Guardrail: the /etc.clientlibs proxy does not resolve a client library folder whose name is the name of a sibling
 * client library folder followed by a dot (e.g. "foo.v1.bar" next to "foo.v1"); its URL returns a 404.
 *
 * Checks the client library folders in src/content and the ones generated by clientlib.config.js.
 *
 * Run with: node test/guardrails/clientlibFolderNames.js
 */
const fs = require("fs");
const path = require("path");

const CONTENT_ROOT = path.join(__dirname, "..", "..");
const JCR_ROOT = path.join(CONTENT_ROOT, "src/content/jcr_root");

/**
 * Collects the client library folders under a directory.
 *
 * @param {String} dir the directory to scan
 * @param {String[]} folders the absolute paths of the client library folders found
 * @returns {String[]} the absolute paths of the client library folders found
 */
function collectClientlibFolders(dir, folders) {
    fs.readdirSync(dir, { withFileTypes: true }).forEach(function(entry) {
        const entryPath = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            collectClientlibFolders(entryPath, folders);
        } else if (entry.name === ".content.xml" &&
            fs.readFileSync(entryPath, "utf8").indexOf("jcr:primaryType=\"cq:ClientLibraryFolder\"") !== -1) {
            folders.push(dir);
        }
    });
    return folders;
}

const folders = collectClientlibFolders(JCR_ROOT, []);
require(path.join(CONTENT_ROOT, "clientlib.config.js")).libs.forEach(function(lib) {
    folders.push(path.join(CONTENT_ROOT, lib.path, lib.name));
});

const namesByParent = {};
folders.forEach(function(folder) {
    const parent = path.dirname(folder);
    namesByParent[parent] = namesByParent[parent] || new Set();
    namesByParent[parent].add(path.basename(folder));
});

let failures = 0;
Object.keys(namesByParent).forEach(function(parent) {
    const names = Array.from(namesByParent[parent]);
    names.forEach(function(name) {
        names.forEach(function(other) {
            if (other.indexOf(name + ".") === 0) {
                console.error("FAIL: client library folder " + path.relative(CONTENT_ROOT, path.join(parent, other)) +
                    " starts with the name of its sibling " + name + "; move it to its own parent folder");
                failures++;
            }
        });
    });
});

if (failures > 0) {
    console.error(failures + " client library folder name check(s) failed");
    process.exit(1);
}
console.log("Checked " + folders.length + " client library folders: OK");
